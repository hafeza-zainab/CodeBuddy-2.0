import assert from 'node:assert/strict';
import test from 'node:test';
import {
  ANALYSIS_DEADLINE_MS,
  ANALYSIS_DEADLINE_SLACK_MS,
  FORGE_SYNCHRONOUS_RUNTIME_LIMIT_MS,
  GEMINI_MAX_ATTEMPTS,
  GEMINI_REQUEST_TIMEOUT_MS,
  GEMINI_RETRY_DELAY_MS,
  GEMINI_STAGE_BUDGET_MS,
  GITHUB_MAX_ATTEMPTS,
  GITHUB_REQUEST_TIMEOUT_MS,
  GITHUB_STAGE_BUDGET_MS,
  JIRA_MAX_ATTEMPTS,
  JIRA_REQUEST_TIMEOUT_MS,
  JIRA_STAGE_BUDGET_MS,
  MAX_SEQUENTIAL_NETWORK_BUDGET_MS,
} from './analysisBudget';

test('named Jira, GitHub, and Gemini phase budgets fit inside the synchronous Forge deadline', () => {
  assert.equal(JIRA_STAGE_BUDGET_MS, 6_000);
  assert.equal(GITHUB_STAGE_BUDGET_MS, 5_000);
  assert.equal(GEMINI_STAGE_BUDGET_MS, 8_000);
  assert.equal(ANALYSIS_DEADLINE_MS, 20_000);
  assert.equal(MAX_SEQUENTIAL_NETWORK_BUDGET_MS, JIRA_STAGE_BUDGET_MS + GITHUB_STAGE_BUDGET_MS + GEMINI_STAGE_BUDGET_MS);
  assert.equal(MAX_SEQUENTIAL_NETWORK_BUDGET_MS + ANALYSIS_DEADLINE_SLACK_MS, ANALYSIS_DEADLINE_MS);
  assert.ok(ANALYSIS_DEADLINE_MS < FORGE_SYNCHRONOUS_RUNTIME_LIMIT_MS);
  assert.equal(JIRA_MAX_ATTEMPTS, 2);
  assert.equal(GITHUB_MAX_ATTEMPTS, 2);
  assert.equal(GEMINI_MAX_ATTEMPTS, 2);
  assert.equal(JIRA_REQUEST_TIMEOUT_MS, 2_500);
  assert.equal(GITHUB_REQUEST_TIMEOUT_MS, 2_500);
  assert.equal(GEMINI_REQUEST_TIMEOUT_MS * GEMINI_MAX_ATTEMPTS, GEMINI_STAGE_BUDGET_MS);
  assert.ok(GEMINI_RETRY_DELAY_MS < GEMINI_STAGE_BUDGET_MS);
});
